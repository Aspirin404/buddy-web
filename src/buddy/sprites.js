export const HAT_LINES = {
  none: '',
  crown:     '   \\^^^/    ',
  tophat:    '   [___]    ',
  propeller: '    -+-     ',
  halo:      '   (   )    ',
  wizard:    '    /^\\     ',
  beanie:    '   (___)    ',
  tinyduck:  '    ,>      ',
}

export function renderSprite(buddy, frame = 0) {
  const frames = BODIES[buddy.species] || BODIES.blob
  const body   = frames[frame % frames.length].map(l => l.replaceAll('{E}', buddy.eye))
  const lines  = [...body]

  if (buddy.hat !== 'none' && !lines[0].trim()) {
    lines[0] = HAT_LINES[buddy.hat] || ''
  }
  if (!lines[0].trim() && frames.every(f => !f[0].trim())) {
    lines.shift()
  }
  return lines
}
